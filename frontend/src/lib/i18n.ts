export const getStoredLanguage = (): LanguageCode => {
  const stored = localStorage.getItem("language") as LanguageCode | null;
  return languages.some((language) => language.code === stored) ? stored! : "en";
};

export const setStoredLanguage = (language: LanguageCode) => {
  localStorage.setItem("language", language);
  window.dispatchEvent(new Event("languagechange"));
};

export const translate = (key: string, language: LanguageCode = getStoredLanguage()) =>
  dictionaries[language][key] ?? dictionaries.en[key] ?? key;

export const applyDocumentLanguage = (language: LanguageCode) => {
  document.documentElement.lang = language === "ca" ? "en-CA" : language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
};
